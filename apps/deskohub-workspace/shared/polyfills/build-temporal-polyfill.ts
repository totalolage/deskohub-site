import { mkdir } from "node:fs/promises";
import { join, resolve } from "node:path";

const polyfillDirectory = import.meta.dir;
const appRoot = resolve(polyfillDirectory, "../..");

/** The polyfill's public path. The `?v=` content hash busts caches. */
const polyfillPath = "/polyfills/temporal.js";
const polyfillFile = join(appRoot, "public", polyfillPath);
/** The generated module that holds the inline `<head>` loader. */
const loaderModule = join(polyfillDirectory, "generated/temporal-loader.ts");

const bundle = async (
  entrypoint: string,
  define: Record<string, string> = {}
) => {
  const build = await Bun.build({
    entrypoints: [join(polyfillDirectory, entrypoint)],
    target: "browser",
    format: "iife",
    minify: true,
    define,
  });
  const [script] = build.outputs;
  if (!build.success || script === undefined) {
    throw new AggregateError(build.logs, `${entrypoint} didn't build.`);
  }
  return script.text();
};

/**
 * Bundles the Temporal polyfill into a classic script that installs the
 * global, and the inline `<head>` loader that requests it only where
 * Temporal is missing or incomplete.
 */
export const buildTemporalPolyfill = async () => {
  const polyfill = await bundle("temporal-polyfill.browser.ts");
  const polyfillUrl = `${polyfillPath}?v=${Bun.hash(polyfill).toString(36)}`;
  const loader = await bundle("temporal-loader.browser.ts", {
    TEMPORAL_POLYFILL_URL: JSON.stringify(polyfillUrl),
  });
  // Inline, `</script` in a string literal would end the loader's element.
  return { polyfill, loader: loader.replaceAll("</", "<\\/") };
};

if (import.meta.main) {
  const { polyfill, loader } = await buildTemporalPolyfill();

  // A stable file name keeps HTML from an earlier deployment working.
  await mkdir(join(polyfillFile, ".."), { recursive: true });
  await Bun.write(polyfillFile, polyfill);
  await Bun.write(
    loaderModule,
    `// Generated by temporal-polyfill:build.\nexport const temporalLoaderScript = ${JSON.stringify(loader)};\n`
  );
}
